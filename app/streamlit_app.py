"""Multimedia AI Content Detection - Streamlit front end.

Run from the project root:

    streamlit run app/streamlit_app.py

The page renders itself from ``mmdetect.registry``: every content type, whether
built or still planned, comes from there, so shipping the week-4 audio detector
means registering it rather than editing this file.
"""
from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

# Make ``src`` importable without installing the package.
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from mmdetect.registry import MODALITIES, get_modality  # noqa: E402
from ui import panels, theme  # noqa: E402

st.set_page_config(
    page_title="Multimedia AI Content Detection",
    page_icon=":material/policy:",
    layout="wide",
    initial_sidebar_state="expanded",
)
theme.inject()


# ---------------------------------------------------------------------------
# Sidebar: project roadmap and model status
# ---------------------------------------------------------------------------
def sidebar() -> None:
    with st.sidebar:
        st.markdown("### Project roadmap")
        for info in MODALITIES.values():
            if info.is_ready and info.is_trained:
                chip, label = "ok", "trained"
            elif info.is_ready:
                chip, label = "todo", "not trained"
            else:
                chip, label = "todo", f"week {info.week}"
            st.markdown(
                f"{info.icon} &nbsp;**{info.label}**"
                f"<span class='mm-chip {chip}'>{label}</span>",
                unsafe_allow_html=True,
            )
            st.caption(f"Week {info.week} - {info.status}")

        st.divider()
        st.markdown("### How it works")
        st.caption(
            "Pick a content type, upload a file, and the matching model scores "
            "how likely it is that the content was produced by AI. Everything "
            "runs locally: nothing is uploaded anywhere."
        )

        st.divider()
        st.markdown("### Read the score carefully")
        st.caption(
            "These detectors output a probability, not proof. They are trained "
            "on specific datasets and get weaker on content that looks nothing "
            "like their training data. Do not use a score on its own to accuse "
            "anyone of anything."
        )


# ---------------------------------------------------------------------------
def main() -> None:
    sidebar()

    theme.hero(
        "Multimedia AI Content Detection",
        "Check whether text, images, audio or video were produced by a human "
        "or generated by AI.",
    )

    theme.step(1, "Choose the content type")

    keys = list(MODALITIES.keys())
    labels = {k: f"{MODALITIES[k].icon}  {MODALITIES[k].label}" for k in keys}

    # segmented_control needs Streamlit >= 1.40; fall back to radio if older.
    if hasattr(st, "segmented_control"):
        chosen = st.segmented_control(
            "Content type",
            options=keys,
            format_func=lambda k: labels[k],
            default=keys[0],
            label_visibility="collapsed",
        )
    else:  # pragma: no cover - only on older Streamlit
        chosen = st.radio(
            "Content type", keys, format_func=lambda k: labels[k],
            horizontal=True, label_visibility="collapsed",
        )

    if not chosen:
        st.caption("Select a content type to continue.")
        return

    info = get_modality(chosen)

    st.markdown(f"**{info.label}** &mdash; {info.description}")
    if info.is_ready:
        cols = st.columns(2)
        cols[0].caption(f"**Dataset**  \n{info.dataset}")
        cols[1].caption(f"**Approach**  \n{info.approach}")

    panels.render(info)

    st.divider()
    with st.expander("Limitations worth knowing before you trust a score"):
        st.markdown(
            """
- **A probability is not proof.** Both detectors output a likelihood. Scores
  near 50% mean the model genuinely cannot tell, and the app labels those
  *Uncertain* rather than guessing.
- **False positives are the expensive error.** Wrongly flagging someone's own
  writing as AI does real harm, so the reported false-positive rate sits next
  to the accuracy figure rather than buried in a report.
- **Text**: trained on HC3 — English question-and-answer prose, with ChatGPT
  as the only AI author. Newer models, other languages, code, heavily edited
  AI text and very short passages all fall outside what it learned.
- **Images**: trained on CIFAKE, which is 32x32 CIFAR-10 photos against Stable
  Diffusion images. Detecting a 4K Midjourney render is a genuinely different
  problem, and accuracy there is well below the test-set number shown in-app.
- **Generators move faster than detectors.** A model trained on today's
  outputs degrades as new ones ship; the reported numbers describe these
  datasets, not the open web.
            """
        )


if __name__ == "__main__":
    main()
